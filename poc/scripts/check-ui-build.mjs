import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const phase=process.argv[2]??'b1-ui';
assert.ok(['b1-ui','b1-business','b2','b2-r2','stage-c','stage-d'].includes(phase),'expected known report phase');
const report=path.join(root,'reports',phase);
await mkdir(report,{recursive:true});
const dist=path.join(root,'dist');
const manifest=JSON.parse(await readFile(path.join(dist,'.vite/manifest.json'),'utf8'));
const entry=await readFile(path.join(dist,manifest['index.html'].file),'utf8');
const table=JSON.parse('['+entry.match(/m\.f=\[([^\]]+)\]/)[1]+']');
const afterRoot=entry.slice(entry.lastIndexOf('.createRoot(document.getElementById("root"))'));
const split=afterRoot.indexOf('}else{');assert.ok(split>0,'explicit runtime window branches missing');
const libBranch=afterRoot.slice(0,split),quickBranch=afterRoot.slice(split+6);
const css=code=>[...new Set([...code.matchAll(/__vite__mapDeps\(\[([\d,]+)\]\)/g)].flatMap(match=>match[1].split(',').map(index=>table[Number(index)])).filter(file=>file.endsWith('.css')))];
const library=css(libBranch),quick=css(quickBranch);
const libCss=manifest['src/library.css'].file,quickCss=manifest['src/quick.css'].file,pocCss=manifest['src/poc.css'].file;
assert.ok(library.includes(libCss));assert.ok(!library.includes(quickCss));assert.ok(!library.includes(pocCss));
assert.ok(quick.includes(quickCss));assert.ok(quick.includes(pocCss));assert.ok(!quick.includes(libCss));
assert.ok(libBranch.includes(path.basename(manifest['src/library/LibraryManager.tsx'].file)));
assert.ok(quickBranch.includes(path.basename(manifest['src/App.tsx'].file)));
for(const file of [...library,...quick])assert.ok((await readFile(path.join(dist,file),'utf8')).length>0);
const prototype=await readFile(path.resolve(root,'../Prompt Shelf 4.2·v2.0/demos/01_V4.11_素材管理UI冻结基线.html'),'utf8');
const baseline=prototype.split('<style>')[1].split('</style>')[0];
assert.ok((await readFile(path.join(root,'src/library.css'),'utf8')).replaceAll('\r\n','\n').includes(baseline.replaceAll('\r\n','\n')),'frozen prototype CSS changed');
const output={result:'PASS',method:'Static inspection of actual Vite production entry preloader dependency arrays; no browser or GUI',entry:manifest['index.html'].file,libraryCss:library,quickCss:quick,windowCssIsolated:true,libraryHasItsOwnDynamicComponent:true,quickHasItsOwnDynamicComponent:true,prototypeStylePreserved:true,visualAcceptance:'NOT_RUN'};
await writeFile(path.join(report,'packaged-css.json'),JSON.stringify(output,null,2)+'\n');
console.log(JSON.stringify(output,null,2));
